const now = new Date().toISOString()

function photosFor(slug: string, title: string) {
  return demoPhotosFor(slug, title)
}

function slotsFor(experienceId: string, durationMinutes: number, maxGuests: number) {
  const offsets = [3, 7, 10, 14]
  return offsets.map((days, index) => {
    const start = new Date()
    start.setDate(start.getDate() + days)
    start.setHours(index % 2 === 0 ? 17 : 10, 0, 0, 0)
    const end = new Date(start.getTime() + durationMinutes * 60_000)
    return {
      id: `${experienceId}-slot-${index + 1}`,
      experience_id: experienceId,
      start_at: start.toISOString(),
      end_at: end.toISOString(),
      capacity: maxGuests,
      booked_count: 0,
      status: 'open',
    }
  })
}

function experience(
  id: string,
  slug: string,
  title: string,
  summary: string,
  description: string,
  price_amount: number,
  duration_minutes: number,
  max_guests: number,
  min_guests: number,
  city: string,
  address: string,
  latitude: number,
  longitude: number,
  category_id: string,
  category_slug: string,
  rating_avg: number,
  rating_count: number,
  host: Experience['host'],
): Experience {
  const photos = photosFor(slug, title)
  return {
    id,
    brand_id: '1',
    host_id: host!.id,
    category_id,
    category_slug,
    slug,
    title,
    summary,
    description,
    language: 'fa',
    price_amount,
    currency: 'IRR',
    duration_minutes,
    max_guests,
    min_guests,
    city,
    address,
    latitude,
    longitude,
    status: 'published',
    rating_avg,
    rating_count,
    created_at: now,
    updated_at: now,
    cover_photo_url: photos.find((photo) => photo.is_cover)?.url ?? photos[0].url,
    photos,
    slots: slotsFor(id, duration_minutes, max_guests),
    host,
  }
}

